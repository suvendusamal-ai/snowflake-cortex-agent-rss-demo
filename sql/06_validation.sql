FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY
WHERE query_start_time>=DATEADD('hour',-2,CURRENT_TIMESTAMP()) AND agents_info IS NOT NULL
ORDER BY query_start_time DESC;
