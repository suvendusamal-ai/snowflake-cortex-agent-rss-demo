SELECT query_id,start_time,user_name,role_name,query_text,agent_type,execution_status,error_code,error_message
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE start_time>=DATEADD('hour',-2,CURRENT_TIMESTAMP()) AND agent_type IS NOT NULL
ORDER BY start_time DESC;

